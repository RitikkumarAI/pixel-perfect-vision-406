import prisma from '../../utils/prisma';
import { AIGateway } from '../ai/ai.gateway';
import { AgentRegistry } from './registry';
import { AgentPrompts } from './prompts';
import { AgentTools } from './tools';

export class AgentExecutionEngine {
  private gateway: AIGateway;

  constructor() {
    this.gateway = new AIGateway();
  }

  public async runAgent(agentId: string, userId: string, workspaceId: string, input: string) {
    const definition = AgentRegistry.find(a => a.id === agentId);
    if (!definition) throw new Error('Agent not found in registry');

    // Make sure user has an Agent record for this workspace to link to
    let agentRecord = await prisma.agent.findFirst({
      where: { workspaceId, name: definition.name }
    });

    if (!agentRecord) {
      agentRecord = await prisma.agent.create({
        data: {
          workspaceId,
          name: definition.name,
          systemPrompt: AgentPrompts[agentId] || "You are an AI assistant."
        }
      });
    }

    const run = await prisma.agentRun.create({
      data: {
        agentId: agentRecord.id,
        userId,
        input,
        status: "RUNNING"
      }
    });

    await this.logStep(run.id, "INFO", `Starting execution for ${definition.name}`);

    try {
      const provider = this.gateway.getProvider();
      
      await this.logStep(run.id, "THOUGHT", "Analyzing input and determining tool usage...");

      // MVP Execution: Route simple intents internally instead of a full recursive ReAct loop
      let result = "";

      if (agentId === 'personal-assistant' && input.toLowerCase().includes('task')) {
        await this.logStep(run.id, "ACTION", "Calling tool: createTask");
        const task = await AgentTools.createTask(workspaceId, input, "Generated by Personal Assistant");
        result = `I have created the task for you: ID ${task.id}`;
      } else if (agentId === 'research-agent' && input.toLowerCase().includes('search')) {
        await this.logStep(run.id, "ACTION", "Calling tool: searchDocuments");
        const docs = await AgentTools.searchDocuments(workspaceId, input.replace('search', '').trim());
        result = `I found ${docs.length} documents matching your query.`;
      } else {
        // Fallback to pure LLM
        const response = await provider.generateCompletion(
          `${AgentPrompts[agentId]}\nUser Request: ${input}`
        );
        result = response;
      }

      await prisma.agentRun.update({
        where: { id: run.id },
        data: {
          status: "COMPLETED",
          result,
          completedAt: new Date()
        }
      });

      await this.logStep(run.id, "INFO", "Execution completed successfully");

      return { runId: run.id, result };
    } catch (error: any) {
      await prisma.agentRun.update({
        where: { id: run.id },
        data: {
          status: "FAILED",
          error: error.message,
          completedAt: new Date()
        }
      });
      await this.logStep(run.id, "ERROR", `Execution failed: ${error.message}`);
      throw error;
    }
  }

  public async getHistory(runId: string) {
    return prisma.agentRun.findUnique({
      where: { id: runId },
      include: { logs: { orderBy: { createdAt: 'asc' } } }
    });
  }

  private async logStep(runId: string, level: string, message: string) {
    await prisma.agentLog.create({
      data: { runId, level, message }
    });
  }
}
